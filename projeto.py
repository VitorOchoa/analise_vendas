# realizar venda

def realizar_venda(id_produto, id_cliente, quantidade, data_venda):
    try:
        df_produto = pd.read_csv('tabela_produto.csv')
        df_cliente = pd.read_csv('tabela_cliente.csv')
        df_venda = pd.read_csv('tabela_venda.csv')

        # validar produto
        if id_produto not in df_produto['id_produto'].values:
            raise ValueError("Produto não encontrado")

        # validar cliente
        if id_cliente not in df_cliente['id_cliente'].values:
            print("Cliente não encontrado. Cadastrando...")
            nome = input("Nome do cliente: ")
            data_nascimento = input("Data de nascimento: ")
            email = input("Email: ")
            telefone = input("Telefone: ")

            id_cliente = cadastrar_cliente(nome, data_nascimento, email, telefone)

        # gerar id venda
        id_venda = df_venda['id_venda'].max() + 1 if not df_venda.empty else 1

        # calcular valor
        valor_unitario = df_produto.loc[
            df_produto['id_produto'] == id_produto, 'valor_unitario'
        ].values[0]

        valor_total = valor_unitario * quantidade

        nova_venda = pd.DataFrame(
            [[id_venda, id_produto, id_cliente, quantidade, data_venda, valor_total]],
            columns=cabecalho_venda
        )

        nova_venda.to_csv('tabela_venda.csv', mode='a', index=False, header=False)

    except Exception as e:
        print("Erro ao realizar venda:", e)

