# TOP 3 CATEGORIAS MAIS VENDIDAS

def top3_categorias_mais_vendidas():
  try:
    df_vendas = pd.read_csv('tabela_venda.csv')
    df_produtos = pd.read_csv('tabela_produto.csv')

    df_vendas_produtos = pd.merge(df_vendas, df_produtos, on='id_produto')

    top_categotia_quantidade = df_vendas_produtos.groupby('categoria_produto')['quantidade'].sum().sort_values(ascending=False).head(3)

    return top_categotia_quantidade
  except:
    print("Erro ao gerar relatório de top 3 categorias mais vendidas")

# PRODUTO MAIS VENDIDO

def produto_mais_vendido():
  try:
    df_vendas = pd.read_csv('tabela_venda.csv')
    df_produtos = pd.read_csv('tabela_produto.csv')

    df_vendas_produtos = pd.merge(df_vendas, df_produtos, on='id_produto')

    produto_mais_vendido = df_vendas_produtos.groupby('nome_produto')['quantidade'].sum().idxmax()

    return produto_mais_vendido
  except:
    print("Erro ao gerar relatório de produto mais vendido")

# TICKET MEDIO POR CLIENTE

def ticket_medio_por_cliente():
  try:
    df_vendas = pd.read_csv('tabela_venda.csv')
    df_clientes = pd.read_csv('tabela_cliente.csv')

    df_vendas_clientes = pd.merge(df_vendas, df_clientes, on='id_cliente')

    ticket_medio_por_cliente = df_vendas_clientes.groupby('id_cliente')['valor_total'].mean()

    return ticket_medio_por_cliente
  except:
    print("Erro ao gerar relatório de ticket médio por cliente")

