# RELACAO DATA X QUANTIDADE VENDIDA

def grafico_data_quantidade():
  df_vendas = pd.read_csv('tabela_venda.csv')

  df_vendas['data_venda'] = pd.to_datetime(df_vendas['data_venda'], format='%Y-%m-%d')

  plt.subplot(dimensao[0], dimensao[1], dimensao[2])
  plt.title('Vendas por Data')
  plt.xlabel('Data')
  plt.ylabel('Quantidade')

  x = df_vendas['data_venda'].dt.day
  y = df_vendas['quantidade']

  plt.plot(x, y , marker='o')

def grafico_categoria_vendas():
  df_vendas = pd.read_csv('tabela_venda.csv')
  df_produtos = pd.read_csv('tabela_produto.csv')

  df_vendas_produtos = pd.merge(df_vendas, df_produtos, on='id_produto')

  top_categotia_quantidade = df_vendas_produtos.groupby('categoria_produto')['quantidade'].sum()

  plt.subplot(dimensao[0], dimensao[1], dimensao[2])

  plt.title('Categorias x Vendas')
  plt.xlabel('Categoria')
  plt.ylabel('Quantidade')
  plt.xticks(rotation=45)

  x = top_categotia_quantidade.index
  y = top_categotia_quantidade.values

  plt.bar(x, y)

def perfil_clientes():
  df_clientes = pd.read_csv('tabela_cliente.csv')

  df_clientes['data_nascimento'] = pd.to_datetime(df_clientes['data_nascimento'], format='%Y-%m-%d')

  df_clientes['idade'] = (pd.to_datetime('today') - df_clientes['data_nascimento']).dt.days // 365

  df_clientes['perfil'] = pd.cut(
        df_clientes['idade'],
        bins=[0, 29, 59, 120],
        labels=['Jovem', 'Adulto', 'Idoso'],
        right=False
    )

  perfil_cliente = df_clientes.groupby('perfil', observed=False).size()

  plt.subplot(dimensao[0], dimensao[1], dimensao[2])
  plt.title('Perfil dos Clientes')
  plt.xlabel('Perfil')
  plt.ylabel('Quantidade')
  plt.xticks(rotation=45)

  x = perfil_cliente.index
  y = perfil_cliente.values

  plt.bar(x, y)

def mostra_grafico():
  plt.tight_layout()
  plt.show()

